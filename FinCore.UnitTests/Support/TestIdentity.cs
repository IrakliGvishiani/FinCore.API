using FinCore.Domain.Entities;
using Microsoft.AspNetCore.Identity;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging.Abstractions;
using Moq;

namespace FinCore.Tests.Support;

/// <summary>EF InMemory context exposing users (and their bank accounts) for UserManager.Users queries.</summary>
internal sealed class UsersDbContext : DbContext
{
    public UsersDbContext(DbContextOptions<UsersDbContext> options) : base(options) { }

    public DbSet<ApplicationUser> AppUsers => Set<ApplicationUser>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<ApplicationUser>().HasKey(u => u.Id);

        var account = modelBuilder.Entity<BankAccount>();
        account.HasKey(a => a.Id);
        account.Ignore(a => a.OutgoingTransfers);
        account.Ignore(a => a.IncomingTransfers);
        account.Ignore(a => a.LedgerEntries);
        account.Ignore(a => a.RowVersion); // SQL Server rowversion; not generated by InMemory
        account.HasOne(a => a.User).WithMany(u => u.BankAccounts).HasForeignKey(a => a.UserId);
    }

    public static UsersDbContext CreateEmpty() =>
        new(new DbContextOptionsBuilder<UsersDbContext>()
            .UseInMemoryDatabase(Guid.NewGuid().ToString())
            .Options);
}

/// <summary>
/// Real UserManager over a Moq store. The store implements the role, lockout,
/// password and queryable interfaces that the services under test need.
/// </summary>
internal sealed class TestIdentity
{
    public Mock<IUserStore<ApplicationUser>> Store { get; } = new();
    public Mock<IUserRoleStore<ApplicationUser>> RoleStore { get; }
    public UserManager<ApplicationUser> Manager { get; }

    public TestIdentity(IQueryable<ApplicationUser>? users = null, IList<string>? roles = null)
    {
        RoleStore = Store.As<IUserRoleStore<ApplicationUser>>();
        var lockoutStore = Store.As<IUserLockoutStore<ApplicationUser>>();
        Store.As<IUserPasswordStore<ApplicationUser>>();
        Store.As<IQueryableUserStore<ApplicationUser>>()
            .Setup(s => s.Users)
            .Returns(users ?? Enumerable.Empty<ApplicationUser>().AsQueryable());

        Store.Setup(s => s.CreateAsync(It.IsAny<ApplicationUser>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(IdentityResult.Success);
        Store.Setup(s => s.UpdateAsync(It.IsAny<ApplicationUser>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(IdentityResult.Success);
        Store.Setup(s => s.GetUserIdAsync(It.IsAny<ApplicationUser>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync((ApplicationUser u, CancellationToken _) => u.Id);

        RoleStore.Setup(s => s.GetRolesAsync(It.IsAny<ApplicationUser>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(roles ?? new List<string>());
        RoleStore.Setup(s => s.IsInRoleAsync(It.IsAny<ApplicationUser>(), It.IsAny<string>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(false);

        lockoutStore.Setup(s => s.GetLockoutEnabledAsync(It.IsAny<ApplicationUser>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(true);

        Manager = new UserManager<ApplicationUser>(
            Store.Object,
            optionsAccessor: null!,
            passwordHasher: new PasswordHasher<ApplicationUser>(),
            userValidators: Array.Empty<IUserValidator<ApplicationUser>>(),
            passwordValidators: Array.Empty<IPasswordValidator<ApplicationUser>>(),
            keyNormalizer: null!,
            errors: new IdentityErrorDescriber(),
            services: null!,
            logger: NullLogger<UserManager<ApplicationUser>>.Instance);
    }

    public void ReturnOnFindById(ApplicationUser? user, string id) =>
        Store.Setup(s => s.FindByIdAsync(id, It.IsAny<CancellationToken>())).ReturnsAsync(user);
}
